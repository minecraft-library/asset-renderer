@unittest.skipUnless(pixels.available() and SWEEP_OUTPUT.is_dir(), "sweep output or pixels absent")
class AgreesWithTheJavaOnRealRenders(unittest.TestCase):
    """The fixture pins the formula; this pins the whole pipeline against the shipped writer.

    The sweep table's ``mean_argb_delta`` was computed by ``ParityMetrics`` in Java over the same
    PNG pair, so agreement here is cross-implementation on real data rather than on four pixels. It
    checks the first ten rows the table holds and every row whose two canvases differ, because the
    pad is what a mismatched row exercises and a scoped run's table holds only the rows that run
    rendered. Rows are read from the table rather than from the directory listing, so a subject
    directory an earlier run left behind is never compared against a row it was not computed for.
    The tolerance is the table's own ``%.4f``, not a fitted epsilon.
    """

    def test_the_first_rows_and_every_mismatched_canvas_agree_to_the_tables_own_precision(self):
        from parity import panel, sweep
        table_path = SWEEP_OUTPUT / "parity-report.tsv"
        if not table_path.is_file():
            self.skipTest("no parity-report.tsv beside the renders")
        table = sweep.read_table(table_path, "entity")
        comparable = sorted((row for row in table.rows if row.delta() is not None
                             and (SWEEP_OUTPUT / row.key / "vanilla.png").is_file()
                             and (SWEEP_OUTPUT / row.key / "java.png").is_file()),
                            key=lambda row: row.key)
        if not comparable:
            self.skipTest("the table holds no row with a delta and a vanilla/java pair")
        java_w, java_h, vanilla_w, vanilla_h = sweep.CANVAS
        mismatched = [row for row in comparable
                      if (row.values[java_w], row.values[java_h])
                      != (row.values[vanilla_w], row.values[vanilla_h])]
        chosen = comparable[:10] + [row for row in mismatched if row not in comparable[:10]]
        for row in chosen:
            where = f"{row.key} (the table holds {len(mismatched)} canvas-mismatched rows)"
            stats = panel.stats(SWEEP_OUTPUT / row.key)
            self.assertEqual(stats["canvas"],
                             {"height": max(int(row.values[java_h]), int(row.values[vanilla_h])),
                              "width": max(int(row.values[java_w]), int(row.values[vanilla_w]))},
                             where)
            self.assertAlmostEqual(stats["mean_over_white"], row.delta(), places=3, msg=where)


ANIMATED_OUTPUT = Path(__file__).resolve().parents[4] / "cache/visual"

#: Half the last place of the sweep table's ``%.4f``, the most a correctly rounded value can be off.
HALF_PLACE = 0.00005


@unittest.skipUnless(pixels.available(), "Pillow/numpy absent")
class FramesAgreeWithTheAnimatedSweeps(unittest.TestCase):
    """The fixture pins the arithmetic; this pins ``frames`` against the Java that wrote the rows.

    Each animated sweep's table was written by ``EntityAnimationParitySweep`` over the frame PNGs
    beside it, so the row's four numbers are re-derived from those PNGs and compared at the table's
    own precision. The first five rows are checked, and every row whose two canvases differ, because
    those are the rows the pad decides.
    """

    def test_the_first_rows_and_every_mismatched_canvas_reproduce_all_four_numbers(self):
        from parity import panel, sweep
        checked = 0
        for name in ("entity-animation", "entity-walk"):
            output = ANIMATED_OUTPUT / f"{name}-parity-vanilla"
            if not (output / "parity-report.tsv").is_file():
                continue
            table = sweep.read_table(output / "parity-report.tsv", name)
            comparable = sorted((row for row in table.rows if row.delta() is not None
                                 and (output / row.key / "vanilla").is_dir()
                                 and (output / row.key / "java").is_dir()),
                                key=lambda row: row.key)
            java_w, java_h, vanilla_w, vanilla_h = sweep.CANVAS
            mismatched = [row for row in comparable
                          if (row.values[java_w], row.values[java_h])
                          != (row.values[vanilla_w], row.values[vanilla_h])]
            for row in comparable[:5] + [row for row in mismatched if row not in comparable[:5]]:
                where = f"{name} {row.key}"
                derived = panel.frames(output / row.key)
                for column in ("mean_argb_delta", "worst_delta", "frame_spread"):
                    self.assertLessEqual(abs(derived[column] - float(row.values[column])),
                                         HALF_PLACE + 1e-12, f"{where} {column}")
                self.assertEqual(derived["worst_frame"], int(row.values["worst_frame"]), where)
                checked += 1
        if not checked:
            self.skipTest("no animated sweep output with a table beside its frames")


class DependencyBoundary(unittest.TestCase):
    """The gate path is stdlib by construction; this is the surface where that stops."""

    def test_available_is_a_bool_and_never_raises(self):
        self.assertIn(pixels.available(), (True, False))

    def test_require_names_the_install_line(self):
        if pixels.available():
            self.assertEqual(len(pixels.missing()), 0)
            return
        with self.assertRaises(MissingDependency) as caught:
            pixels.require("panel stats")
        self.assertIn("pip install", str(caught.exception))

    def test_panel_is_not_importable_without_the_pair(self):
        """panel imports pixels, never numpy - so the boundary holds from the other side too."""
        source = (Path(__file__).resolve().parents[1] / "panel.py").read_text(encoding="utf-8")
        self.assertNotIn("import numpy", source)
        self.assertNotIn("from PIL", source)


