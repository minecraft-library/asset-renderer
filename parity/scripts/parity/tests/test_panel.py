"""The one accept criterion of the probe surface: the Python is *arithmetically* the same probe.

`panel stats` can never be cited as a verdict, so its value rests entirely on agreeing with
the shipped metric. That agreement is pinned here on a fixture whose expected value is transcribed
from ``ParityMetrics.java`` rather than produced by the code under test - a fixture generated by the
implementation would prove only that the implementation is self-consistent.
"""

