#: Hand-derived from ``ParityMetrics.compositeOverWhite`` and ``compositeDiff`` over the four fixture
#: pixels: 0 + 254 + 0 + 765 = 1019, over 4 pixels.
EXPECTED_MEAN_OVER_WHITE = 254.75
EXPECTED_DIFFERING = 2
EXPECTED_COVERAGE = 0.75


@unittest.skipUnless(pixels.available(), "Pillow/numpy absent")
class ArithmeticAgreement(unittest.TestCase):
    """The Python probe must be the same probe, not merely a similar one."""

    def setUp(self):
        from parity import panel
        self.panel = panel
        self.dir = Path(tempfile.mkdtemp()) / "minecraft__fixture"
        self.dir.mkdir(parents=True)
        for name in ("vanilla", "java"):
            (self.dir / f"{name}.png").write_bytes((DATA / f"pixels-2x2-{name}.png").read_bytes())

    def test_over_white_is_byte_for_byte_the_java_formula(self):
        """(c*a + 255*(255-a) + 127) // 255, integer division, on non-negative operands."""
        for channel, alpha, expected in ((255, 255, 255), (0, 255, 0), (0, 128, 127),
                                         (255, 128, 255), (0, 0, 255), (255, 0, 255)):
            self.assertEqual(int(self.panel.over_white(channel, alpha)), expected,
                             f"over_white({channel}, {alpha})")

    def test_mean_over_white_matches_the_shipped_metric(self):
        stats = self.panel.stats(self.dir)
        self.assertAlmostEqual(stats["mean_over_white"], EXPECTED_MEAN_OVER_WHITE, places=6)

    def test_differing_pixels_matches(self):
        self.assertEqual(self.panel.stats(self.dir)["differing_pixels"], EXPECTED_DIFFERING)

    def test_coverage_matches(self):
        coverage = self.panel.stats(self.dir)["coverage"]
        self.assertEqual(coverage["vanilla"] / 4, EXPECTED_COVERAGE)
        self.assertEqual(coverage["java"] / 4, EXPECTED_COVERAGE)

    def test_the_two_metrics_are_reported_under_distinct_names(self):
        """Conflating the 0..765 and 0..1020 scales is a recorded defect."""
        stats = self.panel.stats(self.dir)
        self.assertIn("mean_over_white", stats)
        self.assertIn("mean_abs_argb_1020", stats)
        self.assertNotEqual(stats["mean_over_white"], stats["mean_abs_argb_1020"])

    def test_the_1020_metric_is_the_raw_argb_sum(self):
        # |dA|+|dR|+|dG|+|dB| on raw channels: px1 (0,0,0,127) -> 127, px3 (0,255,255,255) -> 765.
        self.assertAlmostEqual(self.panel.stats(self.dir)["mean_abs_argb_1020"],
                               (127 + 765) / 4, places=6)


