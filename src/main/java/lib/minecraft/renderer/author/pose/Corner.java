package lib.minecraft.renderer.author.pose;

/**
 * Which of a quadruped's four legs a selector addresses.
 */
public enum Corner {

    /**
     * The left foreleg.
     */
    FRONT_LEFT,

    /**
     * The right foreleg.
     */
    FRONT_RIGHT,

    /**
     * The left hindleg.
     */
    HIND_LEFT,

    /**
     * The right hindleg.
     */
    HIND_RIGHT

}
