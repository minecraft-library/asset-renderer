package lib.minecraft.renderer.tooling2.bridge;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import lib.minecraft.renderer.tooling2.kernel.ToolingException;
import org.jetbrains.annotations.NotNull;

import java.util.Map;

/**
 * The four near-passthrough snapshot conversions in one class (10-bridge SS5.5): the legacy payload
 * shapes were already minimal and correct, so each conversion strips the v2 envelope
 * ({@code format}, tooling2 header), re-emits the legacy header + payload key, and drops the
 * v2-only members:
 * <ul>
 *   <li><b>block_tints</b> - drop the {@code dropped[]} member (P45's recorded drop-list is
 *       v2-only) and each row's {@code source} provenance; {@code constant} stays the packed-hex
 *       string.</li>
 *   <li><b>potion_colors</b> / <b>glint_items</b> - payload copied verbatim.</li>
 *   <li><b>color_maps</b> - rename the payload key {@code maps}-&gt;{@code color_maps} and drop each
 *       map's {@code source}; the {@code pixels} base64 is a byte-for-byte string copy.</li>
 * </ul>
 */
final class SnapshotBridge {

    private static final @NotNull String BLOCK_TINTS_HEADER =
        "Generated by ToolingBlockTints. From net.minecraft.client.color.block.BlockColors$createDefault(). "
            + "Run the tooling/blockTints Gradle task to refresh.";
    private static final @NotNull String POTION_COLORS_HEADER =
        "Generated by ToolingPotionColors. From net.minecraft.world.effect.MobEffects clinit. "
            + "Run the tooling/potionColors Gradle task to refresh.";
    private static final @NotNull String GLINT_ITEMS_HEADER =
        "Generated by ToolingGlintItems. Items whose Items registration sets "
            + "DataComponents.ENCHANTMENT_GLINT_OVERRIDE=true. Run the tooling/glintItems Gradle task to refresh.";
    private static final @NotNull String COLOR_MAPS_HEADER =
        "Generated by ToolingColorMaps. From biome colormaps. Run the tooling/colorMaps Gradle task to refresh.";

    private SnapshotBridge() {
    }

    /**
     * Converts one v2 snapshot file into its legacy form.
     *
     * @param legacyResourceName the legacy base name selecting the header + payload transform
     * @param v2 the parsed v2 snapshot object
     * @return the legacy-shaped snapshot object
     * @throws ToolingException if the name is not a snapshot file
     */
    static @NotNull JsonObject convert(@NotNull String legacyResourceName, @NotNull JsonObject v2) {
        return switch (legacyResourceName) {
            case "block_tints.json" -> {
                JsonObject out = LegacyBridge.legacyEnvelope(BLOCK_TINTS_HEADER, v2);
                out.add("tints", dropKey(v2.getAsJsonArray("tints"), "source"));
                yield out;
            }
            case "potion_colors.json" -> {
                JsonObject out = LegacyBridge.legacyEnvelope(POTION_COLORS_HEADER, v2);
                out.add("effects", v2.getAsJsonArray("effects").deepCopy());
                yield out;
            }
            case "glint_items.json" -> {
                JsonObject out = LegacyBridge.legacyEnvelope(GLINT_ITEMS_HEADER, v2);
                out.add("items", v2.getAsJsonArray("items").deepCopy());
                yield out;
            }
            case "color_maps.json" -> {
                JsonObject out = LegacyBridge.legacyEnvelope(COLOR_MAPS_HEADER, v2);
                out.add("color_maps", dropKey(v2.getAsJsonArray("maps"), "source"));
                yield out;
            }
            default -> throw new ToolingException("Not a snapshot resource: '%s'", legacyResourceName);
        };
    }

    /**
     * Copies an array of objects, dropping one member key from each row and preserving the
     * remaining insertion order.
     *
     * @param rows the source array of objects
     * @param drop the member key to drop from each row
     * @return the filtered array
     */
    private static @NotNull JsonArray dropKey(@NotNull JsonArray rows, @NotNull String drop) {
        JsonArray out = new JsonArray(rows.size());
        for (JsonElement element : rows) {
            JsonObject copy = new JsonObject();
            for (Map.Entry<String, JsonElement> member : element.getAsJsonObject().entrySet())
                if (!drop.equals(member.getKey())) copy.add(member.getKey(), member.getValue().deepCopy());
            out.add(copy);
        }
        return out;
    }

}
